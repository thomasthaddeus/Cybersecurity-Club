const { existsSync, readdirSync, readFileSync, writeFileSync } = require('fs');
const { basename, join, resolve } = require('path');

const docsDir = resolve(__dirname, '..', 'docs');
const indexPath = join(docsDir, 'README.md');
const checkOnly = process.argv.includes('--check');

const titleFromMarkdown = (filePath) => {
  const content = readFileSync(filePath, 'utf8');
  const heading = content.match(/^#\s+(.+)$/m);
  return heading ? heading[1].trim() : basename(filePath, '.md');
};

const files = readdirSync(docsDir)
  .filter((file) => file.endsWith('.md') && file.toLowerCase() !== 'readme.md')
  .sort((a, b) => a.localeCompare(b));

const rows = files.map((file) => {
  const absolute = join(docsDir, file);
  return `- [${titleFromMarkdown(absolute)}](${file})`;
});

const content = `# Documentation

This index is generated by \`npm run docs:generate\`.

## Guides

${rows.length ? rows.join('\n') : '- No documentation guides have been added yet.'}
`;

const existing = existsSync(indexPath) ? readFileSync(indexPath, 'utf8') : '';

if (checkOnly) {
  if (existing !== content) {
    console.error('docs/README.md is out of date. Run npm run docs:generate.');
    process.exit(1);
  }
  process.exit(0);
}

writeFileSync(indexPath, content);
console.log('docs/README.md generated.');
